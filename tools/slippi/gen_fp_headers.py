"""Write the test vector headers for platforms/vita/fp.

fp_exact_vectors.h comes from fp_vectors.py, an exact Python model of the
console's fma and MSL sqrtf (copied from the 3DS Slippi port).
ppc_math_vectors.h holds Dolphin's frsqrte results from frsqrte.json.

    python3 tools/slippi/gen_fp_headers.py

The headers are checked in, so the Vita build doesn't need Python for them.
Run this again only if fp_vectors.py or frsqrte.json changes.
"""
import json
from pathlib import Path

import fp_vectors

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'platforms' / 'vita' / 'fp'


def write_frsqrte_header(path):
    data = json.loads((Path(__file__).parent / 'frsqrte.json').read_text())
    lines = ['/* Generated by tools/slippi/gen_fp_headers.py from frsqrte.json */',
             '/* Dolphin ' + data['commit'] + ', ' + data['copyright'] + ', ' + data['license'] + ' */',
             '#include <stdint.h>',
             'static const uint64_t mp_ppc_vectors[][2]={']
    for value, estimate in data['vectors']:
        lines.append('{0x' + value + 'ULL,0x' + estimate + 'ULL},')
    lines.append('};')
    path.write_text('\n'.join(lines) + '\n')


def main():
    fp_vectors.write_header(OUT / 'fp_exact_vectors.h')
    write_frsqrte_header(OUT / 'ppc_math_vectors.h')
    print('wrote', OUT / 'fp_exact_vectors.h')
    print('wrote', OUT / 'ppc_math_vectors.h')


if __name__ == '__main__':
    main()
